// Function with no argument or no parameter.
function print()
{
    console.log("Soniya");
}
print();

// FUNCTION WITH ONE ARGUMENT AND PARAMETER.
function print_myname(name)
{
    console.log(name);
}
print_myname("Soniya K.")
print_myname("Shruti H.")

// Function with two arguments and parameters.
function print_myname_Course(name, course)
{
    console.log(name, course);
}
print_myname_Course("Soniya Kohale ,", "JFSD")